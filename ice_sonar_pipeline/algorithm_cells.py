 'def binary_score_mask(binary_mask, cleaned, context, y_axis, z_axis, ice_z_m):\n'
 '    dy = float(np.nanmean(np.diff(y_axis)))\n'
 '    y_grid, z_grid = np.meshgrid(y_axis, z_axis)\n'
 '    finite_clean = np.isfinite(cleaned)\n'
 '    ice_window = finite_clean & (z_grid >= ice_z_m - 0.85) & (z_grid <= ice_z_m + 0.55)\n'
 '    broader_ice_window = finite_clean & (z_grid >= ice_z_m - 1.25) & (z_grid <= ice_z_m + 0.75)\n'
 '    center_nonice = binary_mask & (np.abs(y_grid) <= 0.30) & (z_grid < ice_z_m - 0.50)\n'
 '    lower_lobe = binary_mask & (z_grid < ice_z_m - 1.10) & (np.abs(y_grid) <= 7.5)\n'
 '\n'
 '    ice_energy_total = safe_energy(cleaned, ice_window)\n'
 '    broader_energy_total = safe_energy(cleaned, broader_ice_window)\n'
 '    ice_energy_in_mask = safe_energy(cleaned, binary_mask & ice_window)\n'
 '    broader_energy_in_mask = safe_energy(cleaned, binary_mask & broader_ice_window)\n'
 '    mask_energy = safe_energy(cleaned, binary_mask)\n'
 '    mask_pixels = int(np.count_nonzero(binary_mask))\n'
 '\n'
 '    ice_energy_capture = ice_energy_in_mask / ice_energy_total if ice_energy_total else 0.0\n'
 '    broader_capture = broader_energy_in_mask / broader_energy_total if broader_energy_total else '
 '0.0\n'
 '    center_residual = safe_energy(cleaned, center_nonice) / mask_energy if mask_energy else 0.0\n'
 '    lobe_residual = safe_energy(cleaned, lower_lobe) / mask_energy if mask_energy else 0.0\n'
 '    left_metrics = binary_left_support_metrics(binary_mask, cleaned, y_axis, z_axis, ice_z_m)\n'
 '\n'
 '    curve_z, curve_weight = binary_extract_curve(binary_mask, cleaned, y_axis, z_axis)\n'
 '    curve_z_reconstructed, curve_interpolated_mask = binary_interpolate_short_gaps(curve_z, '
 'y_axis)\n'
 '    curve_weight_reconstructed = binary_curve_weight_with_interpolation(\n'
 '        curve_weight,\n'
 '        curve_z,\n'
 '        curve_interpolated_mask,\n'
 '    )\n'
 '    active_cols = np.flatnonzero(np.isfinite(curve_z))\n'
 '    if active_cols.size:\n'
 '        y_span = float(y_axis[active_cols.max()] - y_axis[active_cols.min()])\n'
 '        max_gap = binary_max_gap_m(active_cols, y_axis)\n'
 '        smooth_curve = binary_smooth_curve(curve_z, y_axis, sigma_cols=max(1.0, 0.20 / '
 'abs(dy)))\n'
 '        curve_residual = curve_z - smooth_curve\n'
 '        curve_roughness_m = '
 'float(np.nanmedian(np.abs(curve_residual[np.isfinite(curve_residual)]))) if '
 'np.any(np.isfinite(curve_residual)) else 0.0\n'
 '        z_alignment_m = float(abs(np.nanmedian(curve_z[active_cols]) - ice_z_m))\n'
 '    else:\n'
 '        y_span = 0.0\n'
 '        max_gap = float("inf")\n'
 '        curve_roughness_m = 9.0\n'
 '        z_alignment_m = 9.0\n'
 '\n'
 '    y_span_score = min(1.0, y_span / 8.0)\n'
 '    continuity_score = max(0.0, 1.0 - min(max_gap, 2.0) / 2.0) if np.isfinite(max_gap) else 0.0\n'
 '    roughness_score = max(0.0, 1.0 - curve_roughness_m / 0.35)\n'
 '    alignment_score = max(0.0, 1.0 - z_alignment_m / 0.85)\n'
 '    area_fraction = mask_pixels / max(1, int(np.count_nonzero(finite_clean)))\n'
 '\n'
 '    score = (\n'
 '        0.30 * ice_energy_capture\n'
 '        + 0.16 * broader_capture\n'
 '        + 0.13 * y_span_score\n'
 '        + 0.10 * continuity_score\n'
 '        + 0.10 * alignment_score\n'
 '        + 0.05 * roughness_score\n'
 '        + 0.12 * left_metrics["left_support_score"]\n'
 '        - 0.18 * center_residual\n'
 '        - 0.20 * lobe_residual\n'
 '        - 0.06 * abs(area_fraction - 0.035) / 0.035\n'
 '    )\n'
 '    if ice_energy_capture < 0.45:\n'
 '        score -= 0.35 * (0.45 - ice_energy_capture)\n'
 '    if y_span < 2.0:\n'
 '        score -= 0.10 * (2.0 - y_span)\n'
 '    if left_metrics["left_support_needed"] and left_metrics["left_support_score"] < 0.45:\n'
 '        score -= 0.16 * (0.45 - left_metrics["left_support_score"])\n'
 '\n'
 '    return {\n'
 '        "binary_score": float(score),\n'
 '        "ice_energy_capture": float(ice_energy_capture),\n'
 '        "broader_ice_capture": float(broader_capture),\n'
 '        "binary_center_residual": float(center_residual),\n'
 '        "binary_lobe_residual": float(lobe_residual),\n'
 '        "y_span_m": float(y_span),\n'
 '        "max_gap_m": float(max_gap),\n'
 '        "continuity_score": float(continuity_score),\n'
 '        "curve_roughness_m": float(curve_roughness_m),\n'
 '        "z_alignment_m": float(z_alignment_m),\n'
 '        "area_fraction": float(area_fraction),\n'
 '        "mask_pixels": int(mask_pixels),\n'
 '        "curve_z": curve_z,\n'
 '        "curve_weight": curve_weight,\n'
 '        "curve_z_reconstructed": curve_z_reconstructed,\n'
 '        "curve_weight_reconstructed": curve_weight_reconstructed,\n'
 '        "curve_interpolated_mask": curve_interpolated_mask,\n'
 '        "curve_interpolated_point_count": int(np.count_nonzero(curve_interpolated_mask)),\n'
 '        "curve_interpolated_span_m": float(np.count_nonzero(curve_interpolated_mask) * '
 'abs(dy)),\n'
 '        **left_metrics,\n'
 '    }\n'

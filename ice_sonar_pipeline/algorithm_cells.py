 'def adaptive_range_threshold(linear_image, valid_mask, y_axis, z_axis):\n'
 '    base = np.asarray(linear_image, dtype=float).copy()\n'
 '    base[~valid_mask] = np.nan\n'
 '    y_grid, z_grid = np.meshgrid(y_axis, z_axis)\n'
 '    range_grid = np.hypot(y_grid, z_grid)\n'
 '    finite_base = valid_mask & np.isfinite(base)\n'
 '    range_max = float(np.nanmax(range_grid[valid_mask]))\n'
 '    range_edges = np.arange(0.0, range_max + BACKGROUND_BIN_M, BACKGROUND_BIN_M)\n'
 '    if range_edges.size < 2:\n'
 '        raise ValueError("Not enough range bins for adaptive threshold.")\n'
 '    range_centers = 0.5 * (range_edges[:-1] + range_edges[1:])\n'
 '    threshold_curve = np.full(range_centers.shape, np.nan, dtype=float)\n'
 '\n'
 '    for bin_index, (r0, r1) in enumerate(zip(range_edges[:-1], range_edges[1:])):\n'
 '        bin_mask = finite_base & (range_grid >= r0) & (range_grid < r1)\n'
 '        values = base[bin_mask]\n'
 '        if values.size >= MIN_BIN_PIXEL_COUNT:\n'
 '            p_low = np.nanpercentile(values, ADAPTIVE_THRESHOLD_LOW_PERCENTILE)\n'
 '            p_high = np.nanpercentile(values, ADAPTIVE_THRESHOLD_HIGH_PERCENTILE)\n'
 '            threshold_curve[bin_index] = p_low + ADAPTIVE_THRESHOLD_IQR_GAIN * (p_high - p_low)\n'
 '\n'
 '    threshold_curve, smooth_bins = fill_and_smooth_curve(\n'
 '        range_centers,\n'
 '        threshold_curve,\n'
 '        ADAPTIVE_THRESHOLD_SMOOTH_BINS,\n'
 '    )\n'
 '    threshold_grid = np.interp(range_grid, range_centers, threshold_curve, '
 'left=threshold_curve[0], right=threshold_curve[-1])\n'
 '    adaptive = base.copy()\n'
 '    adaptive[base < threshold_grid] = np.nan\n'
 '    adaptive[~valid_mask] = np.nan\n'
 '    adaptive_norm, vmin, vmax = percentile_normalize(adaptive, CLIP_PERCENTILES)\n'
 '    adaptive_norm[~valid_mask] = np.nan\n'
 '    return adaptive_norm, {\n'
 '        "range_centers": range_centers,\n'
 '        "threshold_curve": threshold_curve,\n'
 '        "smooth_bins": smooth_bins,\n'
 '        "norm_vmin": vmin,\n'
 '        "norm_vmax": vmax,\n'
 '    }\n'

 'def percentile_normalize(data, percentiles=(2, 98)):\n'
 '    finite = np.isfinite(data)\n'
 '    if not np.any(finite):\n'
 '        return np.full_like(data, np.nan, dtype=float), np.nan, np.nan\n'
 '    vmin, vmax = np.nanpercentile(data[finite], percentiles)\n'
 '    if not np.isfinite(vmin) or not np.isfinite(vmax) or vmax <= vmin:\n'
 '        vmax = vmin + 1.0\n'
 '    normalized = (data - vmin) / (vmax - vmin)\n'
 '    normalized = np.clip(normalized, 0.0, 1.0)\n'
 '    normalized[~finite] = np.nan\n'
 '    return normalized, float(vmin), float(vmax)\n'
 '\n'
 'def fill_and_smooth_curve(x, curve, smooth_bins, fallback_value=0.0):\n'
 '    good = np.isfinite(curve)\n'
 '    if np.count_nonzero(good) >= 2:\n'
 '        filled = np.interp(x, x[good], curve[good], left=curve[good][0], right=curve[good][-1])\n'
 '    elif np.count_nonzero(good) == 1:\n'
 '        filled = np.full_like(curve, curve[good][0], dtype=float)\n'
 '    else:\n'
 '        filled = np.full_like(curve, fallback_value, dtype=float)\n'
 '    smooth_bins = max(1, int(smooth_bins))\n'
 '    if smooth_bins % 2 == 0:\n'
 '        smooth_bins += 1\n'
 '    kernel = np.ones(smooth_bins, dtype=float) / smooth_bins\n'
 '    return np.convolve(filled, kernel, mode="same"), smooth_bins\n'

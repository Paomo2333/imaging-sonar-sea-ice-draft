 '            final_mask[rows, cols] = True\n'
 '        else:\n'
 '            removed_mask[rows, cols] = True\n'
 '\n'
 '    final_mask &= window_mask\n'
 '    final_mask, left_rescue_meta = binary_apply_left_support_rescue(final_mask, cleaned, '
 'valid_mask, y_axis, z_axis, ice_z_m, config)\n'

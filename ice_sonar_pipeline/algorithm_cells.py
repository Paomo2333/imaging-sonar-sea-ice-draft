 '    meta["left_edge_gap_before"] = before["left_edge_gap_m"]\n'
 '    edge_gap_trigger = before["left_edge_gap_m"] >= LEFT_EDGE_EXTENSION_MIN_GAP_M\n'
 '    capture_trigger = before["left_ice_energy_capture"] < LEFT_RESCUE_CAPTURE_TRIGGER\n'
 '\n'
 '    if (not before["left_support_needed"]) or (before["left_support_score"] >= '
 'LEFT_RESCUE_MIN_SUPPORT_SCORE and not edge_gap_trigger and not capture_trigger):\n'
 '        meta["left_support_after"] = before["left_support_score"]\n'
 '        meta["left_edge_gap_after"] = before["left_edge_gap_m"]\n'
 '        return final_mask, meta\n'
 '\n'
 '    dy = float(np.nanmean(np.diff(y_axis)))\n'
 '    dz = float(np.nanmean(np.diff(z_axis)))\n'
 '    y_grid, z_grid = np.meshgrid(y_axis, z_axis)\n'
 '    left_down_m = min(float(config["window_down_m"]), LEFT_RESCUE_MAX_DOWN_M)\n'
 '    left_window = (\n'
 '        valid_mask\n'
 '        & np.isfinite(cleaned)\n'
 '        & (y_grid <= LEFT_SUPPORT_Y_MAX_M)\n'
 '        & (z_grid >= ice_z_m - left_down_m)\n'
 '        & (z_grid <= ice_z_m + config["window_up_m"])\n'
 '    )\n'
 '    left_values = cleaned[left_window]\n'
 '    if left_values.size < 20:\n'
 '        meta["left_support_after"] = before["left_support_score"]\n'
 '        meta["left_edge_gap_after"] = before["left_edge_gap_m"]\n'
 '        return final_mask, meta\n'
 '\n'
 '    local_high = float(np.nanpercentile(left_values, config["high_q"]))\n'
 '    local_low = float(np.nanpercentile(left_values, config["low_q"]))\n'
 '    local_low = min(local_low, local_high)\n'
 '    meta["left_rescue_threshold_high"] = local_high\n'
 '    meta["left_rescue_threshold_low"] = local_low\n'
 '\n'
 '    seed_mask = left_window & (cleaned >= local_high)\n'
 '    weak_mask = left_window & (cleaned >= local_low)\n'
 '    rescue_peak_threshold = local_low if (capture_trigger or edge_gap_trigger) else local_high\n'
 '    rescue_raw = binary_component_hysteresis(seed_mask, weak_mask)\n'
 '\n'
 '    ridge_mask = np.zeros_like(rescue_raw, dtype=bool)\n'
 '    half_width_px = meters_to_pixels(LEFT_RESCUE_RIDGE_HALF_WIDTH_M, dz, minimum=1)\n'
 '    left_cols = np.flatnonzero(np.any(left_window, axis=0))\n'
 '    for col in left_cols:\n'
 '        rows = np.flatnonzero(left_window[:, col] & np.isfinite(cleaned[:, col]))\n'
 '        if rows.size == 0:\n'
 '            continue\n'
 '        values = cleaned[rows, col]\n'
 '        if not np.any(np.isfinite(values)):\n'
 '            continue\n'
 '        peak_row = rows[int(np.nanargmax(values))]\n'
 '        if cleaned[peak_row, col] < rescue_peak_threshold:\n'
 '            continue\n'
 '        row0 = max(0, peak_row - half_width_px)\n'
 '        row1 = min(rescue_raw.shape[0], peak_row + half_width_px + 1)\n'
 '        ridge_mask[row0:row1, col] = True\n'
 '\n'
 '    ridge_seed = ridge_mask & weak_mask & (cleaned >= rescue_peak_threshold)\n'
 '    rescue_raw = binary_component_hysteresis(seed_mask | ridge_seed, weak_mask)\n'
 '    rescue_raw &= ridge_mask\n'
 '    close_y = meters_to_pixels(config["closing_y_m"], dy, minimum=1)\n'
 '    close_z = meters_to_pixels(config["closing_z_m"], dz, minimum=1)\n'
 '    if close_y > 0 and close_z > 0:\n'
 '        rescue_raw = binary_closing(rescue_raw, footprint=np.ones((close_z, close_y), '
 'dtype=bool))\n'
 '\n'
 '    min_pixels = max(1, int(round(0.5 * config["min_area_m2"] / max(abs(dy * dz), 1e-9))))\n'
 '    rescue_raw = remove_small_objects(rescue_raw, min_size=min_pixels, connectivity=2)\n'
 '\n'
 '    rescue_mask = np.zeros_like(rescue_raw, dtype=bool)\n'
 '    component_labels = label(rescue_raw, connectivity=2)\n'
 '    for region in regionprops(component_labels, intensity_image=np.nan_to_num(cleaned, '
 'nan=0.0)):\n'
 '        rows = region.coords[:, 0]\n'
 '        cols = region.coords[:, 1]\n'
 '        y_min = float(y_axis[int(cols.min())])\n'
 '        y_max = float(y_axis[int(cols.max())])\n'
 '        z_min = float(z_axis[int(rows.min())])\n'
 '        z_max = float(z_axis[int(rows.max())])\n'
 '        y_span = y_max - y_min\n'
 '        z_span = z_max - z_min\n'
 '        y_centroid = float(y_axis[int(round(region.centroid[1]))])\n'
 '        z_centroid = float(z_axis[int(round(region.centroid[0]))])\n'
 '        area_m2 = float(region.area * abs(dy) * abs(dz))\n'
 '\n'
 '        enough_support = (y_span >= LEFT_RESCUE_MIN_Y_SPAN_M) or (area_m2 >= 0.5 * '
 'config["min_area_m2"])\n'
 '        near_ice = (z_max >= ice_z_m - left_down_m) and (z_min <= ice_z_m + '
 'config["window_up_m"])\n'
 '        center_line_like = (abs(y_centroid) <= 0.35) and (y_span <= 0.50) and (z_span >= 1.20) '
 'and (z_centroid < ice_z_m - 0.20)\n'
 '        lower_lobe_like = (z_centroid < ice_z_m - left_down_m) or ((z_centroid < ice_z_m - 0.95) '
 'and (y_span <= 4.50))\n'
 '\n'
 '        if enough_support and near_ice and not center_line_like and not lower_lobe_like:\n'
 '            rescue_mask[rows, cols] = True\n'
 '\n'
 '    rescue_mask &= left_window\n'
 '    rescue_mask &= ~final_mask\n'
 '    if not np.any(rescue_mask):\n'
 '        meta["left_support_after"] = before["left_support_score"]\n'
 '        meta["left_edge_gap_after"] = before["left_edge_gap_m"]\n'
 '        return final_mask, meta\n'
 '\n'
 '    merged = final_mask | rescue_mask\n'
 '    after = binary_left_support_metrics(merged, cleaned, y_axis, z_axis, ice_z_m)\n'
 '    meta["left_support_after"] = after["left_support_score"]\n'
 '    meta["left_edge_gap_after"] = after["left_edge_gap_m"]\n'
 '    improved_score = after["left_support_score"] > before["left_support_score"] + 0.02\n'
 '    improved_edge = before["left_edge_gap_m"] - after["left_edge_gap_m"] > 0.25\n'
 '    if not (improved_score or improved_edge):\n'
 '        return final_mask, meta\n'
 '\n'
 '    meta["left_rescue_mask"] = rescue_mask\n'
 '    meta["left_rescue_applied"] = 1\n'
 '    meta["left_rescue_pixel_count"] = int(np.count_nonzero(rescue_mask))\n'
 '    return merged, meta\n'

 '        "adaptive_image": prepared["adaptive_image"],\n'
 '        "adaptive_meta": prepared["adaptive_meta"],\n'
 '        "context": prepared["context"],\n'
 '        "cleaned": cleaned,\n'
 '        "masks": masks,\n'
 '    }\n'

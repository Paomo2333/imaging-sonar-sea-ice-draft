 'def suppress_artifacts(adaptive_image, valid_mask, y_axis, z_axis, context, config):\n'
 '    cleaned = np.asarray(adaptive_image, dtype=float).copy()\n'
 '    cleaned[~valid_mask] = np.nan\n'
 '    dy = context["dy"]\n'
 '    dz = context["dz"]\n'
 '    ice_z = context["initial_ice_z"]\n'
 '    center_core_mask = context["masks"]["center_core"]\n'
 '\n'
 '    weak_mask = valid_mask & np.isfinite(cleaned) & (cleaned < config["weak_floor"])\n'
 '    cleaned[weak_mask] = np.nan\n'
 '\n'
 '    side_cols = (np.abs(y_axis) >= CENTER_SIDE_INNER_M) & (np.abs(y_axis) <= '
 'CENTER_SIDE_OUTER_M)\n'
 '    side_values = cleaned[:, side_cols]\n'
 '    side_support = np.full(cleaned.shape[0], np.nan, dtype=float)\n'
 '    for row in range(cleaned.shape[0]):\n'
 '        row_values = side_values[row, :]\n'
 '        finite_row = np.isfinite(row_values)\n'
 '        if np.count_nonzero(finite_row) >= 3:\n'
 '            side_support[row] = np.nanpercentile(row_values[finite_row], '
 'CENTER_SIDE_PERCENTILE)\n'
 '\n'
 '    support_finite = np.isfinite(side_support)\n'
 '    if np.count_nonzero(support_finite) >= 2:\n'
 '        side_support = np.interp(z_axis, z_axis[support_finite], side_support[support_finite], '
 'left=0.0, right=0.0)\n'
 '    else:\n'
 '        side_support = np.zeros_like(z_axis, dtype=float)\n'
 '\n'
 '    center_threshold = np.maximum(side_support + CENTER_EXCESS, config["center_min_level"])\n'
 '    center_artifact_mask = (\n'
 '        center_core_mask\n'
 '        & np.isfinite(cleaned)\n'
 '        & (cleaned > center_threshold[:, None])\n'
 '        & (side_support[:, None] < CENTER_SIDE_PRESERVE_LEVEL)\n'
 '    )\n'
 '    cleaned[center_artifact_mask] = cleaned[center_artifact_mask] * '
 'config["center_attenuation"]\n'
 '\n'
 '    binary = np.isfinite(cleaned) & (cleaned >= COMPONENT_THRESHOLD)\n'
 '    component_labels = label(binary, connectivity=2)\n'
 '    lobe_mask = np.zeros_like(binary, dtype=bool)\n'
 '    for region in regionprops(component_labels, intensity_image=np.nan_to_num(cleaned, '
 'nan=0.0)):\n'
 '        rows = region.coords[:, 0]\n'
 '        cols = region.coords[:, 1]\n'
 '        z_max = float(z_axis[int(rows.max())])\n'
 '        z_centroid = float(z_axis[int(round(region.centroid[0]))])\n'
 '        y_width = float(y_axis[int(cols.max())] - y_axis[int(cols.min())]) if cols.size else '
 '0.0\n'
 '        area_m2 = float(region.area * abs(dy) * abs(dz))\n'
 '        below_ice = z_max < ice_z - 0.45 or z_centroid < ice_z - LOBE_Z_MARGIN_M\n'
 '        compact_or_low = (y_width <= LOBE_MAX_WIDTH_M) or (area_m2 < 0.80)\n'
 '        if below_ice and compact_or_low:\n'
 '            lobe_mask[rows, cols] = True\n'
 '    cleaned[lobe_mask] = cleaned[lobe_mask] * config["lobe_attenuation"]\n'
 '\n'
 '    cleaned[np.isfinite(cleaned) & (cleaned < config["post_floor"])] = np.nan\n'
 '    cleaned[~valid_mask] = np.nan\n'
 '    cleaned = np.clip(cleaned, 0.0, 1.0)\n'
 '\n'
 '    suppress_mask = np.full(cleaned.shape, np.nan, dtype=float)\n'
 '    suppress_mask[weak_mask] = 1.0\n'
 '    suppress_mask[center_artifact_mask] = 2.0\n'
 '    suppress_mask[lobe_mask] = 3.0\n'
 '    return cleaned, {\n'
 '        "weak_mask": weak_mask,\n'
 '        "center_mask": center_artifact_mask,\n'
 '        "lobe_mask": lobe_mask,\n'
 '        "suppress_mask": suppress_mask,\n'
 '    }\n'

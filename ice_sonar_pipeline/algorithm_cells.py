 'def binary_segment_ice(cleaned, valid_mask, y_axis, z_axis, ice_z_m, config):\n'
 '    dy = float(np.nanmean(np.diff(y_axis)))\n'
 '    dz = float(np.nanmean(np.diff(z_axis)))\n'
 '    y_grid, z_grid = np.meshgrid(y_axis, z_axis)\n'
 '    cleaned = np.asarray(cleaned, dtype=float).copy()\n'
 '    cleaned[~valid_mask] = np.nan\n'
 '\n'
 '    window_mask = (\n'
 '        valid_mask\n'
 '        & np.isfinite(cleaned)\n'
 '        & (z_grid >= ice_z_m - config["window_down_m"])\n'
 '        & (z_grid <= ice_z_m + config["window_up_m"])\n'
 '    )\n'
 '    values = cleaned[window_mask]\n'
 '    if values.size < 10:\n'
 '        empty = np.zeros_like(valid_mask, dtype=bool)\n'
 '        meta = {\n'
 '            "raw_mask": empty,\n'
 '            "seed_mask": empty,\n'
 '            "weak_mask": empty,\n'
 '            "removed_mask": empty,\n'
 '            "threshold_high": np.nan,\n'
 '            "threshold_low": np.nan,\n'
 '        }\n'
 '        meta.update(binary_empty_left_rescue_meta(valid_mask.shape))\n'
 '        return empty, meta\n'
 '\n'
 '    threshold_high = float(np.nanpercentile(values, config["high_q"]))\n'
 '    threshold_low = float(np.nanpercentile(values, config["low_q"]))\n'
 '    threshold_low = min(threshold_low, threshold_high)\n'
 '\n'
 '    seed_mask = window_mask & (cleaned >= threshold_high)\n'
 '    weak_mask = window_mask & (cleaned >= threshold_low)\n'
 '    raw_mask = binary_component_hysteresis(seed_mask, weak_mask)\n'
 '\n'
 '    close_y = meters_to_pixels(config["closing_y_m"], dy, minimum=1)\n'
 '    close_z = meters_to_pixels(config["closing_z_m"], dz, minimum=1)\n'
 '    if close_y > 0 and close_z > 0:\n'
 '        raw_mask = binary_closing(raw_mask, footprint=np.ones((close_z, close_y), dtype=bool))\n'
 '\n'
 '    open_y = meters_to_pixels(config["opening_y_m"], dy, minimum=1)\n'
 '    open_z = meters_to_pixels(config["opening_z_m"], dz, minimum=1)\n'
 '    if open_y > 0 and open_z > 0:\n'
 '        raw_mask = binary_opening(raw_mask, footprint=np.ones((open_z, open_y), dtype=bool))\n'
 '\n'
 '    min_pixels = max(1, int(round(config["min_area_m2"] / max(abs(dy * dz), 1e-9))))\n'
 '    raw_mask = remove_small_objects(raw_mask, min_size=min_pixels, connectivity=2)\n'
 '    hole_pixels = max(1, int(round(config["hole_area_m2"] / max(abs(dy * dz), 1e-9))))\n'
 '    raw_mask = remove_small_holes(raw_mask, area_threshold=hole_pixels, connectivity=2)\n'
 '    raw_mask &= valid_mask\n'
 '\n'
 '    component_labels = label(raw_mask, connectivity=2)\n'
 '    final_mask = np.zeros_like(raw_mask, dtype=bool)\n'
 '    removed_mask = np.zeros_like(raw_mask, dtype=bool)\n'
 '    for region in regionprops(component_labels, intensity_image=np.nan_to_num(cleaned, '
 'nan=0.0)):\n'
 '        rows = region.coords[:, 0]\n'
 '        cols = region.coords[:, 1]\n'
 '        y_min = float(y_axis[int(cols.min())])\n'
 '        y_max = float(y_axis[int(cols.max())])\n'
 '        z_min = float(z_axis[int(rows.min())])\n'
 '        z_max = float(z_axis[int(rows.max())])\n'
 '        y_span = y_max - y_min\n'
 '        z_span = z_max - z_min\n'
 '        y_centroid = float(y_axis[int(round(region.centroid[1]))])\n'
 '        z_centroid = float(z_axis[int(round(region.centroid[0]))])\n'
 '        area_m2 = float(region.area * abs(dy) * abs(dz))\n'
 '\n'
 '        near_ice = (z_max >= ice_z_m - config["window_down_m"]) and (z_min <= ice_z_m + '
 'config["window_up_m"])\n'
 '        enough_support = (y_span >= config["min_y_span_m"]) or (area_m2 >= '
 'config["min_area_m2"])\n'
 '        center_line_like = (abs(y_centroid) <= 0.35) and (y_span <= 0.50) and (z_span >= 1.20) '
 'and (z_centroid < ice_z_m - 0.20)\n'
 '        lower_lobe_like = (z_centroid < ice_z_m - 0.95) and (y_span <= 4.50)\n'
